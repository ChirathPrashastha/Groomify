    private void btnDeleteOwnerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteOwnerActionPerformed
        if(selectedOwnerId == 0){
            JOptionPane.showMessageDialog(null, "Please select the row that needed to delete", "Infromation", JOptionPane.INFORMATION_MESSAGE);
        }else{
            int result = JOptionPane.showConfirmDialog(null, "Are you sure you want to remove owner ID : " + selectedOwnerId + " permanently ?", "Confirmation", JOptionPane.YES_NO_OPTION);
            
            if(result == JOptionPane.YES_OPTION){
                boolean isSuccess = ownerController.deleteOwner(selectedOwnerId);
            
                if(isSuccess){
                    JOptionPane.showMessageDialog(null, "Owner deleted successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
                
                    loadTable();
                    clearFields();
                }else{
                    JOptionPane.showMessageDialog(null, "Failed to delete the owner!", "Failed", JOptionPane.ERROR_MESSAGE);
                }
            }else{
                clearFields();
                selectedOwnerId = 0;
            }
        }
    }//GEN-LAST:event_btnDeleteOwnerActionPerformed

    private void searchKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_searchKeyReleased
        if(txtSearch.getText().isEmpty()){
            loadTable();
        }else{
            String id = txtSearch.getText();

            Owner searchResult = ownerController.searchOwner(id);
                    
            if(searchResult != null){
                DefaultTableModel model = (DefaultTableModel)tblOwners.getModel();
                model.setRowCount(0);
                        
                Object[] row = {searchResult.getOwnerId(), searchResult.getName(), searchResult.getContact(), searchResult.getAddress(), searchResult.getEmail()};
                model.addRow(row);
            }else{
                loadTable();
            }
        }
    }//GEN-LAST:event_searchKeyReleased

    private void loadTable(){
        DefaultTableModel model = (DefaultTableModel)tblOwners.getModel();
        
        model.setRowCount(0);
        
        ArrayList<Owner> ownerList = ownerController.getAllOwners();
        
        for(Owner owner : ownerList){
            Object[] row = {owner.getOwnerId(), owner.getName(), owner.getContact(), owner.getAddress(), owner.getEmail()};
            model.addRow(row);
        }
    }
    
    private void clearFields(){
        txtSearch.setText("");
        txtName.setText("");
        txtContact.setText("+94");
        txtAddress.setText("");
        txtEmail.setText("");
        lblError.setText("");
    }
    
    private boolean validateFields(){
        if(txtContact.getText().matches("\\+?[0-9]+") == false || txtContact.getText().length() != 12 || txtContact.getText().length() != 12){
            txtContact.setForeground(new Color(163,45,45));
            lblError.setText("Please enter a valid contact number");
            
            return false;
        }else{
            txtContact.setForeground(Color.BLACK);
        }
        
        if(txtEmail.getText().contains("@") == false || txtEmail.getText().contains(".") == false){
            txtEmail.setForeground(new Color(163,45,45));
            lblError.setText("Please enter a valid email");
            
            return false;
        }else{
            txtEmail.setForeground(Color.BLACK);
        }
        
        return true;
    }
    
