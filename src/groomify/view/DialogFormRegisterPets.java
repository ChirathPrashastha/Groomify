    private void btnRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterActionPerformed
        if(cmbOwner.getSelectedIndex()==0 || txtPetName.getText().isEmpty() || txtBreed.getText().isEmpty()){
            JOptionPane.showMessageDialog(null, "Please fill all the fields", "Information", JOptionPane.INFORMATION_MESSAGE);
        }else{
            boolean isSuccess = petController.addPet(new Pet(txtPetName.getText(), cmbSpecies.getSelectedItem().toString(), txtBreed.getText(), cmbCoatType.getSelectedItem().toString(), selectedOwnerId));
            
            if(isSuccess){
                    JOptionPane.showMessageDialog(null, "Pet registered successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
                    clearFields();
            }else{
                    JOptionPane.showMessageDialog(null, "Failed to register the pet!", "Failed", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnRegisterActionPerformed

    private void cmbOwnerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbOwnerActionPerformed
        if(cmbOwner.getSelectedIndex() > 0){
            selectedOwnerId = ownerController.getOwnerIdbyOwnerName(cmbOwner.getSelectedItem().toString());
            
            if(selectedOwnerId != 0){
                lblOwner.setText("Owner ID: " + selectedOwnerId);
            }
        }
    }//GEN-LAST:event_cmbOwnerActionPerformed

    private void clearFields(){
        txtPetName.setText("");
        txtBreed.setText("");
        cmbOwner.setSelectedIndex(0);
        selectedOwnerId = 0;
        cmbSpecies.setSelectedIndex(0);
        cmbCoatType.setSelectedIndex(0);
        lblOwner.setText("Owner");
    }
    
